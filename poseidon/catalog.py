BY_SLUG = {tool["slug"]: tool for tool in TOOLS}


def find_tool(value):
    value = value.casefold().strip()
    return BY_SLUG.get(value) or next((t for t in TOOLS if t["name"].casefold() == value), None)


def search_tools(query="", category=None, platform=None):
    words = query.casefold().split()
    return [
        t
        for t in TOOLS
        if (not category or t["category"] == category)
        and (not platform or platform in t["platforms"])
        and all(
            word in " ".join((t["name"], t["slug"], t["category"], t["summary"])).casefold()
            for word in words
        )
    ]
